def build_help(page, E, SITE, L):
    by = {d['slug']: d for d in L}
    cards = []
    for g in GUIDES:
        cards.append(f'<a class="card" href="/help/{g["slug"]}"><h3 style="margin-top:0">{E(g["title"])}</h3><p class="muted">{E(g["answer"][:150].rsplit(" ",1)[0])}…</p></a>')
        b = [f'<div class="wrap narrow"><nav class="crumbs" aria-label="Breadcrumb"><a href="/help">Help for grown-ups</a></nav>',
             f'<h1 style="margin-top:.35em">{E(g["title"])}</h1>',
             f'<div class="answer card"><p class="lead" style="margin:0">{E(g["answer"])}</p></div>']
        for sec in g['sections']:
            h, paras = sec[0], sec[1]
            b.append(f'<h2>{E(h)}</h2>')
            if paras:
                b += [f'<p>{E(p)}</p>' for p in paras]
            if len(sec) > 2:
                b.append('<ol>' + ''.join(f'<li>{E(x)}</li>' for x in sec[2]) + '</ol>')
        tries = [by[s] for s in g['try'] if s in by]
        if tries:
            b.append('<div class="card"><h2 style="margin-top:0">Try it with a free lesson</h2><ul>' +
                     ''.join(f'<li><a href="/{d["slug"]}">{d["code"]} {E(d["title"])}</a> (video, key words and <a href="/{d["slug"]}-workbook">free workbook</a>)</li>' for d in tries) +
                     '</ul><p><a class="btn" href="/year-7">See all Year 7 lessons</a></p></div>')
        b.append('<section id="faq"><h2>Questions parents ask</h2>' + ''.join(
            f'<details class="q"><summary>{E(q)}</summary><p class="a">{E(a)}</p></details>' for q, a in g['faq']) + '</section>')
        b.append('<p style="margin-top:28px"><a href="/help">← All guides for grown-ups</a></p>'
                 '<p class="small">Celly School is not a diagnosis or treatment service. If you are worried about your child\'s reading or learning, talk to their school\'s SENCo or a qualified specialist.</p></div>')
        url = f'{SITE}/help/{g["slug"]}'
        ld = [{'@context': 'https://schema.org', '@type': 'Article', 'headline': g['title'], 'description': g['desc'], 'url': url,
               'inLanguage': 'en-GB', 'author': {'@type': 'Organization', 'name': 'Celly School', 'url': SITE},
               'publisher': {'@type': 'Organization', 'name': 'Celly School', 'url': SITE}},
              {'@context': 'https://schema.org', '@type': 'FAQPage', 'mainEntity': [
                  {'@type': 'Question', 'name': q, 'acceptedAnswer': {'@type': 'Answer', 'text': a}} for q, a in g['faq']]},
              {'@context': 'https://schema.org', '@type': 'BreadcrumbList', 'itemListElement': [
                  {'@type': 'ListItem', 'position': 1, 'name': 'Help for grown-ups', 'item': SITE + '/help'},
                  {'@type': 'ListItem', 'position': 2, 'name': g['title'], 'item': url}]}]
        page(f'help/{g["slug"]}.html', g['seo'], g['desc'], '\n'.join(b), 'hp', jsonld=ld)
    body = ('<div class="wrap"><h1 style="margin-top:36px">Help for grown-ups</h1>'
            '<p class="lead">Short, practical guides for parents, tutors and teachers helping a child with dyslexia (or anyone who finds reading hard) with Year 7 science.</p>'
            f'<div class="grid">{"".join(cards)}</div>'
            '<p style="margin-top:28px">More about how our lessons work: <a href="/about">For parents, tutors and teachers</a>.</p></div>')
    page('help.html', 'Help for parents and teachers: dyslexia and Year 7 science | Celly School',
         'Practical guides for helping a dyslexic child with KS3 Year 7 science: at home, remembering science words, multisensory teaching, resources for SENCOs, and families in the Gulf.', body, 'hp')
    return ['help'] + [f'help/{g["slug"]}' for g in GUIDES]
